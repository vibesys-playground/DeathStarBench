"""social-network-k8s dataset: the seed of the task's generated social network, and its digest.

The dataset itself (users, the follower graph, the seeded posts and timelines) is
generated by the Go module evaluator/internal/dataset from this seed: the seed Job
writes it into the data tier (evaluator/cmd/seed), and the generator and the
accuracy check rebuild it from the dataset file the benchmark writes, which is this
value as JSON ({"seed": ..., "digest": ...}). The digest is the Go dataset's, so a
generator or a seed built from a different dataset refuses to run.
"""

from __future__ import annotations

from dataclasses import dataclass

SEED = 407708418465  # 0x5eed50c1a1, internal/dataset DefaultSeed
DIGEST = "af53262d9dc775b2214a481d8165fcfec987c13b311161923167488f07035348"


@dataclass(frozen=True)
class Dataset:
    seed: int
    digest: str


def generate() -> Dataset:
    return Dataset(SEED, DIGEST)
