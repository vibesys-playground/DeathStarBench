"""The hotel-k8s dataset's spec: what the task's data is generated from.

`generate()` returns SPEC; vibesys-evaluator writes it as the sample's dataset file
(`dataset.json`), and `python dataset.py PATH` writes the same file for the accuracy check.
The data itself is a pure function of the spec, generated by the Go package
evaluator/internal/dataset (its single owner): every hotel and user, and for every night of the
rate window the rooms already booked. The benchmark's generator and the accuracy oracle
generate what they need from the spec in memory; the MongoDB servers get the data from a
snapshot on the node that `hotel-data ensure` builds once per dataset version (snapshot.py,
evaluator/internal/snapshot), so a sample copies files instead of inserting documents.

Shape at SPEC (see evaluator/internal/dataset/dataset.go): 1,500,000 hotels in 20
metropolitan areas, each with a profile, a location, 1 to 5 rate plans over 2027-2028, a
rating, a price, a room capacity and the rooms booked on each of the window's 730 nights
(about 1.09 billion reservation-db "nights" documents); 500,000 users. About 112 GB of
documents and indexes as MongoDB holds them in memory (about 50 GB compressed on disk).
"""

from __future__ import annotations

import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

# The Go generator's format (dataset.Format): the spec names which generator it is for.
FORMAT = 3


@dataclass(frozen=True)
class Spec:
    """The dataset file: these fields, by name (evaluator/internal/dataset's Spec)."""

    format: int
    seed: int
    hotels: int
    users: int


# Changing any field changes the task: results measured on different datasets do not compare.
SPEC = Spec(format=FORMAT, seed=0x686F74656C2D7633, hotels=1_500_000, users=500_000)  # "hotel-v3"


def generate() -> Spec:
    """The task's dataset spec (vibesys-evaluator's `dataset`): every process gets the same."""
    return SPEC


def encode(spec: Spec) -> bytes:
    """The dataset file: the spec as JSON, field by field (what vibesys-evaluator writes too)."""
    return json.dumps(asdict(spec), allow_nan=False, separators=(",", ":")).encode() + b"\n"


if __name__ == "__main__":
    # python dataset.py PATH: write the dataset file (the accuracy check's oracle reads it).
    Path(sys.argv[1]).write_bytes(encode(generate()))
